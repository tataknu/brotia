"""Loan schedules and exposure: a line-by-line port of app/src/domain/schedule.ts (CONTRACT §E.8).

Dates are 'YYYY-MM-DD' strings compared lexically, exactly as the app does.
"""

from __future__ import annotations

import calendar
from datetime import date
from decimal import ROUND_HALF_UP, Decimal
from typing import Any

from app.models import Installment, Loan

SCHEDULE_LABELS = {
    "bullet": "Bullet (single payment at maturity)",
    "monthly": "Monthly",
    "quarterly": "Quarterly",
    "semiannual": "Every 6 months",
    "at_harvest": "At harvest",
    "custom": "Custom",
}

STEP_MONTHS = {"monthly": 1, "quarterly": 3, "semiannual": 6}


def round2(n: float) -> float:
    """Math.round(n * 100) / 100 (half away from zero for positives, like JS for money amounts)."""
    return float(Decimal(str(n * 100)).quantize(Decimal("1"), rounding=ROUND_HALF_UP)) / 100


def iso(d: date | str) -> str:
    return d if isinstance(d, str) else d.isoformat()


def add_months(iso_date: str, months: int) -> str:
    """Calendar months, clamped to month end (Jan 31 + 1 month = Feb 28/29). Port of dates.ts addMonths."""
    y, m, d = (int(x) for x in iso_date[:10].split("-"))
    total = y * 12 + (m - 1) + months
    ny, nm0 = divmod(total, 12)
    nd = min(d, calendar.monthrange(ny, nm0 + 1)[1])
    return date(ny, nm0 + 1, nd).isoformat()


def generate_installments(
    type_: str,
    origination_date: str,
    maturity_date: str,
    amount: float,
    harvest_date: str | None = None,
) -> list[Installment]:
    """Port of generateInstallments:
    - bullet: one installment at maturity.
    - monthly / quarterly / semiannual: equal principal installments stepping back from maturity (the last
      falls on maturity; every due date is after origination); split in whole cents, leftover cents go to
      the last installments, so the sum equals `amount` exactly.
    - at_harvest: one equal installment per yearly harvest from harvest_date (first harvest after origination)
      up to maturity; with no harvest inside the term, one installment at maturity.
    - custom: [] (the user enters installments).
    """
    total = round2(amount)
    if type_ == "custom":
        return []
    if type_ == "bullet":
        return [Installment(due_date=maturity_date, amount=total)]
    if type_ == "at_harvest":
        h = harvest_date
        if not (h and origination_date < h <= maturity_date):
            return [Installment(due_date=maturity_date, amount=total)]
        dates = []
        for i in range(100):
            d = add_months(h, 12 * i)
            if d > maturity_date:
                break
            dates.append(d)
        return _split_equal(dates, total)
    step = STEP_MONTHS.get(type_, 1)
    dates: list[str] = []
    for i in range(600):
        d = add_months(maturity_date, -i * step)
        if d <= origination_date:
            break
        dates.append(d)
    if not dates:
        return [Installment(due_date=maturity_date, amount=total)]
    dates.reverse()
    return _split_equal(dates, total)


def _split_equal(dates: list[str], total: float) -> list[Installment]:
    n = len(dates)
    cents = int(round(total * 100))
    base = cents // n
    rem = cents - base * n
    return [Installment(due_date=d, amount=round2((base + (1 if i >= n - rem else 0)) / 100)) for i, d in enumerate(dates)]


def installments_total(installments: list[Installment]) -> float:
    return round2(sum(i.amount for i in installments))


def _plan(loan: Loan) -> list[Installment]:
    return list(loan.installments) if loan.installments else [Installment(due_date=loan.maturity_date, amount=loan.amount)]


def outstanding_at(loan: Loan | None, as_of: date | str) -> float:
    """§E.8: 0 before origination; installments due on or before as_of are paid; an empty plan behaves
    like a bullet at maturity; never negative. 0 without a loan."""
    if loan is None:
        return 0.0
    d = iso(as_of)
    if d < loan.origination_date:
        return 0.0
    paid = sum(i.amount for i in _plan(loan) if i.due_date <= d)
    return max(0.0, round2(loan.amount - paid))


def next_installment(loan: Loan | None, as_of: date | str) -> Installment | None:
    """§E.8: earliest installment of the same plan with dueDate > as_of, or None."""
    if loan is None:
        return None
    d = iso(as_of)
    later = sorted((i for i in _plan(loan) if i.due_date > d), key=lambda i: i.due_date)
    return later[0] if later else None


def make_loan(
    schedule_type: str,
    origination_date: str,
    maturity_date: str,
    amount: float,
    currency: str = "USD",
    harvest_date: str | None = None,
    installments: list[dict[str, Any]] | None = None,
) -> Loan:
    """Loan with installments generated by the schedule type (custom: the given installments)."""
    if schedule_type == "custom":
        inst = [Installment(due_date=i["dueDate"], amount=round2(i["amount"])) for i in (installments or [])]
    else:
        inst = generate_installments(schedule_type, origination_date, maturity_date, amount, harvest_date)
    return Loan(
        origination_date=origination_date,
        maturity_date=maturity_date,
        amount=round2(amount),
        currency=currency,
        schedule_type=schedule_type,
        installments=inst,
    )
