@dataclass(frozen=True)
class SourceInfo:
    id: str
    label: str
    licence_tier: LicenceTier
    resolution: str


#: Source registry. Licence tiers per ADR-0011 D1 (CATALOG licence table).
SOURCES: dict[str, SourceInfo] = {}


def register(id: str, label: str, licence_tier: LicenceTier, resolution: str) -> SourceInfo:
    info = SourceInfo(id, label, licence_tier, resolution)
    SOURCES[id] = info
    return info


