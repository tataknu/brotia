def info(source: str) -> SourceInfo:
    return SOURCES.get(source) or SourceInfo(source, source, "unresolved", "n/a")


def _iso(v: Any) -> str | None:
    if v is None:
        return None
    if isinstance(v, datetime):
        return config.iso_utc(v)
    if isinstance(v, date):
        return v.isoformat()
    return str(v)


def build(
    source: str,
    *,
    observed_at: Any = None,
    fetched_at: Any = None,
    resolution: str | None = None,
    stale: bool = False,
    estimated: bool = False,
    note: str | None = None,
    data_tier: DataTier = "enhanced",
    licence_tier: LicenceTier | None = None,
    source_label: str | None = None,
) -> Provenance:
    """Provenance for one value. fetched_at defaults to now (UTC)."""
    i = info(source)
    return Provenance(
        source=source,
        source_label=source_label or i.label,
        observed_at=_iso(observed_at),
        fetched_at=_iso(fetched_at) or config.iso_utc(),
        resolution=resolution or i.resolution,
        licence_tier=licence_tier or i.licence_tier,
        data_tier=data_tier,
        stale=stale,
        estimated=estimated,
        note=note,
    )


def from_fetch(source: str, result: Any, *, observed_at: Any = None, estimated: bool = False,
               note: str | None = None, data_tier: DataTier = "enhanced",
               resolution: str | None = None) -> Provenance:
    """From an app.http.FetchResult: copies fetched_at and stale; appends the refresh error to note."""
    notes = [n for n in [note, f"stale: {result.error}" if getattr(result, "stale", False) and result.error else None] if n]
    return build(
        source,
        observed_at=observed_at,
        fetched_at=result.fetched_at,
        stale=bool(result.stale),
        estimated=estimated,
        note="; ".join(notes) or None,
        data_tier=data_tier,
        resolution=resolution,
    )


def unavailable(source: str, reason: str, *, data_tier: DataTier = "enhanced",
                estimated: bool = False) -> Provenance:
    """For a value that could not be obtained: value null / points [], note = reason."""
    return build(source, observed_at=None, note=f"unavailable: {reason}", data_tier=data_tier, estimated=estimated)


def derived(note: str, *, inputs: Iterable[Provenance] = (), observed_at: Any = None,
            data_tier: DataTier = "enhanced") -> Provenance:
    """For computed values: stale/estimated propagate from inputs; licence is the weakest input tier;
    observed_at defaults to the latest input observed_at."""
    inputs = [p for p in inputs if p is not None]
    order = {"commercial_ok": 0, "demo_only": 1, "unresolved": 2}
    tier: LicenceTier = "commercial_ok"
    for p in inputs:
        if order[p.licence_tier] > order[tier]:
            tier = p.licence_tier
    obs = observed_at
    if obs is None:
        dates = [p.observed_at for p in inputs if p.observed_at]
        obs = max(dates) if dates else None
    srcs = sorted({p.source for p in inputs})
    full_note = note + (f" (inputs: {', '.join(srcs)})" if srcs else "")
    return build(
        "derived",
        observed_at=obs,
        stale=any(p.stale for p in inputs),
        estimated=any(p.estimated for p in inputs),
        note=full_note,
        data_tier=data_tier,
        licence_tier=tier if inputs else "unresolved",
    )


def fixture(note: str = "fixture: illustrative") -> Provenance:
    return build("fixture", note=note, estimated=True)


def data_tier_for(country: str | None) -> DataTier:
    """CL -> 'enhanced', anything else -> 'standard' (CONTRACT §A Country)."""
    return "enhanced" if (country or "").upper() == "CL" else "standard"
